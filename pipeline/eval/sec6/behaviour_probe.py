"""Fixed-context behaviour probe (direction A follow-up). Question: on IDENTICAL second-turn contexts, does the dV arm's
policy prefer 'Step 2 | locate' (a new region of the original image) over re_examine / fallback / commit more than the
orig arm at matched steps? Contexts are not generated by either arm: they are the library-A SFT model's own E1
trajectories (traj_A_sft.jsonl, samples 0 and 1 of each item) replayed through the crop environment up to the receipt
of crop 1; only trajectories whose first turn is a legal crop and that have a second turn are used.

For each context and model, score log P(word | prefix) for word in WORDS by teacher forcing the canonical tokens of
' <word>\\n' after the prefix '<think>\\nStep 2 |' (vLLM prompt_logprobs), then normalise over WORDS.
Writes probe_rows.jsonl (uid, sample_idx, model, probs) and probe_summary.json:
  mean P(word) per model; paired item-bootstrap (2,000, seed 0, cluster = uid) 95% CI of
  P_dv(locate) - P_orig(locate) at each step and of P_dv160(locate) - P_dv40(locate).
Usage: python behaviour_probe.py --traj <traj_A_sft.jsonl> --out <dir> --models name=path ...
"""
import argparse
import collections
import json
import os
import random
import sys
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--traj", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--code-dir", required=True)
ap.add_argument("--pool", required=True)
ap.add_argument("--models", nargs="+", required=True)
ap.add_argument("--limit", type=int, default=0)
ap.add_argument("--samples", default="0,1", help="sample_idx values of the SFT trajectories used as contexts")
a = ap.parse_args()
sys.path.insert(0, a.code_dir)
sys.path.insert(0, os.environ["EASYR1_DIR"])
sys.path.insert(0, os.environ["EVAL_DIR"])

import pandas as pd  # noqa: E402
from transformers import AutoProcessor  # noqa: E402
from vllm import LLM, SamplingParams  # noqa: E402
from verl.utils.dataset import process_image  # noqa: E402

import caption_env as CENV  # noqa: E402
from caption_contracts import raw_image_prompt  # noqa: E402

WORDS = ("locate", "re_examine", "fallback", "commit", "abstain")
MIN_PX, MAX_PX, MAX_LEN = 1024, 589824, 11264
out = Path(a.out)
out.mkdir(parents=True, exist_ok=True)

df = pd.concat([pd.read_parquet(f"{a.pool}/val.parquet"), pd.read_parquet(f"{a.pool}/vstar_holdout.parquet")],
               ignore_index=True)
rows = {r["uid"]: r for _, r in df.iterrows()}


def contexts():
    """(uid, sample_idx, msgs, images) after crop 1 of each SFT trajectory whose first turn is a legal crop."""
    res = []
    for line in open(a.traj):
        t = json.loads(line)
        if str(t["sample_idx"]) not in a.samples.split(","):
            continue
        turns = t["turns"]
        if not turns or (turns[0].get("parsed") or {}).get("kind") != "grounding" or len(turns) < 2:
            continue
        row = rows[t["uid"]]
        env = CENV.CropEnv(row["images"][0])
        msgs = [{"role": "system", "content": row["system"]},
                {"role": "user", "content": [{"type": "text", "text": row["env_head"] + "\n"}, {"type": "image"},
                                             {"type": "text", "text": row["env_tail"]}]}]
        imgs = [process_image(env.images[0], MIN_PX, MAX_PX)]
        r = env.step(dict(turns[0]["parsed"]))
        if r is None:
            continue
        msgs.append({"role": "assistant", "content": turns[0].get("text_in_history", turns[0]["text"])})
        msgs.append({"role": "user", "content": [{"type": "text", "text": r["head"] + "\n"}, {"type": "image"},
                                                 {"type": "text", "text": r["tail"]}]})
        imgs.append(process_image(env.images[-1], MIN_PX, MAX_PX))
        res.append((t["uid"], t["sample_idx"], msgs, imgs))
    return res[: a.limit] if a.limit else res


CTX = contexts()
print(f"contexts: {len(CTX)}", flush=True)


def score(name, path):
    proc = AutoProcessor.from_pretrained(path, trust_remote_code=True)
    llm = LLM(model=path, trust_remote_code=True, dtype="bfloat16", gpu_memory_utilization=0.85,
              max_model_len=MAX_LEN, limit_mm_per_prompt={"image": 10}, seed=0)
    conts = {w: proc.tokenizer.encode(f" {w}\n", add_special_tokens=False) for w in WORDS}
    prompts, meta = [], []
    for uid, s, msgs, imgs in CTX:
        text = proc.apply_chat_template(msgs, add_generation_prompt=True, tokenize=False) + "<think>\nStep 2 |"
        enc = proc(imgs, [text], add_special_tokens=False, return_tensors="pt")
        raw = raw_image_prompt(enc["input_ids"][0].tolist(), enc["image_grid_thw"].tolist(), proc)
        for w in WORDS:
            prompts.append({"prompt_token_ids": raw + conts[w], "multi_modal_data": {"image": imgs}})
            meta.append((uid, s, w, len(conts[w])))
    sp = SamplingParams(max_tokens=1, temperature=0.0, prompt_logprobs=0)
    outs = llm.generate(prompts, sp, use_tqdm=False)
    lp = collections.defaultdict(dict)
    for (uid, s, w, k), o in zip(meta, outs):
        ids = o.prompt_token_ids[-k:]
        pls = o.prompt_logprobs[-k:]
        lp[(uid, s)][w] = sum(pl[t].logprob for pl, t in zip(pls, ids))
    del llm
    import gc
    import torch
    gc.collect()
    torch.cuda.empty_cache()
    res = {}
    for key, d in lp.items():
        m = max(d.values())
        z = sum(pow(2.718281828459045, v - m) for v in d.values())
        res[key] = {w: pow(2.718281828459045, d[w] - m) / z for w in WORDS}
    return res


# One process per model: vLLM does not return GPU memory when an LLM object is deleted inside a process (recovery fix
# 10-21 after the first battery pass crashed on the second model; protocol unchanged).
ALL = {}
if os.environ.get("PROBE_CHILD") != "1":
    import subprocess
    for spec in a.models:
        name = spec.split("=", 1)[0]
        dst = out / f"probe_rows_{name}.jsonl"
        if not dst.exists():
            argv = [sys.executable, __file__] + [x for x in sys.argv[1:] if x != "--models" and x not in a.models] + ["--models", spec]
            subprocess.run(argv, env=dict(os.environ, PROBE_CHILD="1"), check=True)
        ALL[name] = {}
        for line in open(dst):
            r = json.loads(line)
            ALL[name][(r["uid"], r["sample_idx"])] = r["probs"]
        print(f"[{name}] done", {w: round(sum(p[w] for p in ALL[name].values()) / len(ALL[name]), 4) for w in WORDS},
              flush=True)
else:
    name, path = a.models[0].split("=", 1)
    res = score(name, path)
    tmp = out / f"probe_rows_{name}.jsonl.tmp"
    with open(tmp, "w") as f:
        for (uid, s), p in res.items():
            f.write(json.dumps(dict(uid=uid, sample_idx=s, model=name, probs=p)) + "\n")
    tmp.rename(out / f"probe_rows_{name}.jsonl")
    sys.exit(0)


def paired(m1, m2, word="locate"):
    by = collections.defaultdict(list)
    for key in ALL[m1]:
        if key in ALL[m2]:
            by[key[0]].append(ALL[m1][key][word] - ALL[m2][key][word])
    U = sorted(by)
    item = [sum(by[u]) / len(by[u]) for u in U]
    rng = random.Random(0)
    bs = sorted(sum(rng.choice(item) for _ in U) / len(U) for _ in range(2000))
    return dict(n_items=len(U), mean=sum(item) / len(U), lo=bs[50], hi=bs[1949])


summ = dict(n_contexts=len(CTX), mean={m: {w: sum(p[w] for p in v.values()) / len(v) for w in WORDS} for m, v in ALL.items()},
            d_locate={}, d_re_examine={})
for st in (40, 80, 120, 160):
    if f"dv{st}" in ALL and f"orig{st}" in ALL:
        summ["d_locate"][st] = paired(f"dv{st}", f"orig{st}")
        summ["d_re_examine"][st] = paired(f"dv{st}", f"orig{st}", "re_examine")
if "dv160" in ALL and "dv40" in ALL:
    summ["dv160_minus_dv40_locate"] = paired("dv160", "dv40")
if "orig160" in ALL and "orig40" in ALL:
    summ["orig160_minus_orig40_locate"] = paired("orig160", "orig40")
json.dump(summ, open(out / "probe_summary.json", "w"), indent=1)
print(json.dumps(summ, indent=1))
